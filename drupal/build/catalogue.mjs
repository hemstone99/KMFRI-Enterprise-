/**
 * Exports the service catalogue (src/data/serviceCatalogue.ts — the single source of truth)
 * to the Drupal module as data/catalogue.json, and copies the images it uses.
 *
 * Every node carries its web address segments and precomputed counts, so the PHP side
 * renders exactly what the React app shows. Run through drupal/build/build.mjs.
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { tsImport } from 'tsx/esm/api';

export async function exportCatalogue(root, moduleDir) {
  const cat = await tsImport(pathToFileURL(path.join(root, 'src/data/serviceCatalogue.ts')).href, import.meta.url);
  const { STATION_IMAGES } = await tsImport(pathToFileURL(path.join(root, 'src/data/stationServices.ts')).href, import.meta.url);
  const { SERVICE_CATALOGUE, CATALOGUE_TOTAL, FEATURED_ITEMS, ECITIZEN_URL, availabilityOf, itemsUnder, lowestFee, onlineCount, slugOf } = cat;

  const images = new Set();
  // '/images/x.webp' (public/) -> 'images/x.webp' (module-relative)
  const img = (src) => {
    if (!src) return null;
    const rel = src.replace(/^\/+/, '');
    images.add(rel);
    return rel;
  };

  const item = (i) => ({
    no: i.no,
    name: i.name,
    blurb: i.blurb ?? null,
    fee_kes: i.feeKES ?? null,
    fee_unit: i.feeUnit ?? null,
    fee_note: i.feeNote ?? null,
    availability: availabilityOf(i),
    online: i.onboarded,
    priority: i.priority,
    service_slug: i.serviceSlug ?? null,
    note: i.note ?? null,
  });

  const node = (n, parents) => {
    const slugs = [...parents, slugOf(n)];
    return {
      id: n.id,
      slug: slugOf(n),
      path: slugs.join('/'),
      title: n.title,
      register_label: n.registerLabel ?? null,
      summary: n.summary ?? null,
      highlight: n.highlight ?? null,
      image: img(n.image),
      service_slug: n.serviceSlug ?? null,
      count: itemsUnder(n).length,
      online: onlineCount(n),
      from_kes: lowestFee(n) ?? null,
      // Division-only marketing fields
      ...(parents.length === 0 && {
        tagline: n.tagline,
        benefits: n.benefits,
        credentials: n.credentials ?? [],
        gallery: n.gallery.map((g) => ({ src: img(g.src), alt: g.alt })),
      }),
      items: (n.items ?? []).map(item),
      children: (n.children ?? []).map((c) => node(c, slugs)),
    };
  };

  const data = {
    _comment: 'Generated by drupal/build/catalogue.mjs from src/data/serviceCatalogue.ts — do not edit by hand.',
    ecitizen_url: ECITIZEN_URL,
    total: CATALOGUE_TOTAL,
    online_total: SERVICE_CATALOGUE.reduce((sum, d) => sum + onlineCount(d), 0),
    featured: FEATURED_ITEMS.map(({ item: i }) => i.no),
    divisions: SERVICE_CATALOGUE.map((d) => node(d, [])),
    // Station slug (place name) => banner photo, for the station pages.
    station_images: Object.fromEntries(Object.entries(STATION_IMAGES).map(([slug, src]) => [slug, img(src)])),
  };
  fs.writeFileSync(path.join(moduleDir, 'data/catalogue.json'), JSON.stringify(data, null, 1) + '\n');
  fs.writeFileSync(path.join(moduleDir, 'sql/004_service_catalogue.sql'), catalogueSql(data.divisions));

  // Ship the images (and their -sm variants) with the module.
  let copied = 0;
  for (const rel of images) {
    for (const variant of [rel, rel.replace(/\.webp$/, '-sm.webp')]) {
      const from = path.join(root, 'public', variant);
      const to = path.join(moduleDir, variant);
      if (!fs.existsSync(from)) continue;
      if (fs.existsSync(to) && fs.statSync(to).size === fs.statSync(from).size) continue;
      fs.mkdirSync(path.dirname(to), { recursive: true });
      fs.copyFileSync(from, to);
      copied++;
    }
  }
  console.log(`catalogue.json: ${data.total} services in ${data.divisions.length} divisions; ${copied} images copied`);
}

/**
 * sql/004_service_catalogue.sql: the catalogue as tables in kmfri_services_db, so the
 * database carries the same divisions, groups, services and tariffs as the website.
 * 005_catalogue_tariffs.sql then publishes the priced services as pricing tiers.
 */
function catalogueSql(divisions) {
  const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
  const service = (slug) => (slug ? `(SELECT id FROM services WHERE slug = ${q(slug)})` : 'NULL');
  const nodes = [];
  const items = [];
  // Sub-groups belong to the portfolio of the group above them.
  const walk = (n, parent, division, depth, portfolio) => {
    const slug = n.service_slug ?? portfolio;
    nodes.push(`(${[q(n.id), q(parent?.id), q(division.id), depth, q(n.slug), q(n.path), q(n.title), q(n.register_label), q(n.summary), service(slug), nodes.length + 1].join(', ')})`);
    for (const i of n.items) {
      items.push(`(${[i.no, q(n.id), q(i.name), q(i.blurb), i.fee_kes ?? 'NULL', q(i.fee_unit), q(i.fee_note), q(i.availability), q(i.priority), service(i.service_slug), items.length + 1].join(', ')})`);
    }
    for (const c of n.children) walk(c, n, division, depth + 1, slug);
  };
  for (const d of divisions) walk(d, null, d, 0, null);

  return `-- ====================================================================
-- 004: KMFRI Service Catalogue (citizen-facing services, register rows 44–167)
--
-- GENERATED by drupal/build/catalogue.mjs from src/data/serviceCatalogue.ts —
-- do not edit by hand; change the catalogue source and run the build.
--
--   catalogue_nodes  Division → Service group → [Sub-group], with web address paths
--   catalogue_items  One row per register service: tariff, unit, how it is obtained
-- ====================================================================

USE kmfri_services_db;

SET FOREIGN_KEY_CHECKS = 0;
DROP VIEW IF EXISTS v_catalogue_tariffs;
DROP TABLE IF EXISTS catalogue_items;
DROP TABLE IF EXISTS catalogue_nodes;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE catalogue_nodes (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  parent_id VARCHAR(60) NULL,
  division_id VARCHAR(60) NOT NULL,
  depth TINYINT UNSIGNED NOT NULL COMMENT '0 = division, 1 = service group, 2 = sub-group',
  slug VARCHAR(80) NOT NULL,
  url_path VARCHAR(200) NOT NULL UNIQUE COMMENT 'Web address below /enterprise/catalogue/',
  title VARCHAR(200) NOT NULL,
  register_label VARCHAR(200) NULL COMMENT 'Heading as written in the KMFRI services register',
  summary TEXT NULL,
  service_id INT UNSIGNED NULL COMMENT 'Service portfolio carrying the quotation flow',
  display_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (parent_id) REFERENCES catalogue_nodes(id) ON DELETE CASCADE,
  FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE SET NULL,
  INDEX idx_division (division_id),
  INDEX idx_order (display_order)
) ENGINE=InnoDB COMMENT='Service Catalogue hierarchy (divisions, groups, sub-groups)';

CREATE TABLE catalogue_items (
  register_no SMALLINT UNSIGNED NOT NULL PRIMARY KEY COMMENT 'Row number in the KMFRI services register',
  node_id VARCHAR(60) NOT NULL,
  name VARCHAR(255) NOT NULL,
  blurb TEXT NULL,
  fee_kes DECIMAL(12, 2) NULL COMMENT 'Official tariff; NULL = on quotation / see fee_note',
  fee_unit VARCHAR(60) NULL COMMENT 'Charging unit as stated in the register',
  fee_note VARCHAR(60) NULL COMMENT 'Non-numeric tariff, e.g. Free',
  availability ENUM('online', 'partial', 'office', 'planned') NOT NULL COMMENT 'online = eCitizen; partial = digitised; office = at a KMFRI centre; planned = future platform',
  priority ENUM('High', 'Medium', 'Low') NOT NULL DEFAULT 'High',
  service_id INT UNSIGNED NULL,
  display_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (node_id) REFERENCES catalogue_nodes(id) ON DELETE CASCADE,
  FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE SET NULL,
  INDEX idx_node (node_id),
  INDEX idx_service (service_id),
  FULLTEXT KEY ft_search (name, blurb)
) ENGINE=InnoDB COMMENT='Citizen-facing services from the KMFRI services register';

INSERT INTO catalogue_nodes (id, parent_id, division_id, depth, slug, url_path, title, register_label, summary, service_id, display_order) VALUES
${nodes.join(',\n')};

INSERT INTO catalogue_items (register_no, node_id, name, blurb, fee_kes, fee_unit, fee_note, availability, priority, service_id, display_order) VALUES
${items.join(',\n')};
`;
}
